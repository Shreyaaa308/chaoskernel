
import os
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import (
    getSampleStyleSheet,
    ParagraphStyle,
)
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    Preformatted,
)


def generate_markdown_report(chaos_payload):
    """
    Generate a Markdown report from ChaosKernel analysis.
    """

    if not isinstance(chaos_payload, dict):
        raise ValueError("chaos_payload must be a dictionary")

    target_service = chaos_payload.get(
        "target_service", "Unknown Service"
    )
    threat_type = chaos_payload.get(
        "threat_type", "Unknown Threat"
    )
    severity = chaos_payload.get(
        "severity", "Unknown Severity"
    )
    components = chaos_payload.get(
        "blast_radius_nodes", {}
    )
    mitigation_summary = chaos_payload.get(
        "mitigation_summary",
        "No mitigation summary provided."
    )
    code_patch = chaos_payload.get(
        "code_patch",
        "No code patch provided."
    )

    report = f"""# ChaosKernel - Chaos Analysis Report

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

## 1. Target Service
{target_service}

## 2. Threat Analysis
- **Threat Type:** {threat_type}
- **Severity:** {severity}

## 3. Blast Radius Analysis

| Component | Health Status |
|---|---|
"""

    for component, status in components.items():
        report += f"| {component} | {status} |\n"

    report += f"""
## 4. Recommended Mitigation

{mitigation_summary}

## 5. Suggested Code Patch

```python
{code_patch}
```

---
*Generated by ChaosKernel - Adversarial SRE Engine*
"""

    return report


def generate_pdf_report(
    chaos_payload,
    output_path="Chaos_Hardening_Spec.pdf"
):
    """
    Generate a PDF hardening report from ChaosKernel analysis.
    """

    if not isinstance(chaos_payload, dict):
        raise ValueError("chaos_payload must be a dictionary")

    target_service = chaos_payload.get(
        "target_service", "Unknown Service"
    )
    threat_type = chaos_payload.get(
        "threat_type", "Unknown Threat"
    )
    severity = chaos_payload.get(
        "severity", "Unknown Severity"
    )
    components = chaos_payload.get(
        "blast_radius_nodes", {}
    )
    mitigation_summary = chaos_payload.get(
        "mitigation_summary",
        "No mitigation summary provided."
    )
    code_patch = chaos_payload.get(
        "code_patch",
        "No code patch provided."
    )

    if not isinstance(components, dict):
        raise ValueError("blast_radius_nodes must be a dictionary")

    document = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        rightMargin=50,
        leftMargin=50,
        topMargin=50,
        bottomMargin=50,
    )

    styles = getSampleStyleSheet()
    story = []

    # Code formatting
    code_style = ParagraphStyle(
        "CodeBlock",
        parent=styles["Code"],
        fontName="Courier",
        fontSize=9,
        leading=12,
        backColor=colors.HexColor("#F2F2F2"),
        borderPadding=8,
    )

    # Report title
    story.append(
        Paragraph(
            "ChaosKernel - Chaos Hardening Report",
            styles["Title"],
        )
    )
    story.append(Spacer(1, 20))

    # Report details
    story.append(
        Paragraph(
            f"<b>Target Service:</b> {escape(str(target_service))}",
            styles["Normal"],
        )
    )
    story.append(
        Paragraph(
            f"<b>Threat Type:</b> {escape(str(threat_type))}",
            styles["Normal"],
        )
    )
    story.append(
        Paragraph(
            f"<b>Severity:</b> {escape(str(severity))}",
            styles["Normal"],
        )
    )
    story.append(
        Paragraph(
            f"<b>Generated:</b> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
            styles["Normal"],
        )
    )
    story.append(Spacer(1, 20))

    # Blast radius section
    story.append(
        Paragraph(
            "Blast Radius Analysis",
            styles["Heading2"],
        )
    )
    story.append(Spacer(1, 10))

    table_data = [
        ["Component", "Health Status"]
    ]

    status_styles = []

    # Add component statuses and their colours
    for component, status in components.items():
        status = str(status).upper()

        table_data.append([
            str(component),
            status,
        ])

        row_number = len(table_data) - 1

        if status == "HEALTHY":
            status_color = colors.HexColor("#D1FAE5")
        elif status == "DEGRADED":
            status_color = colors.HexColor("#FED7AA")
        elif status == "FAILED":
            status_color = colors.HexColor("#FECACA")
        else:
            status_color = colors.HexColor("#E5E7EB")

        status_styles.append(
            (
                "BACKGROUND",
                (1, row_number),
                (1, row_number),
                status_color,
            )
        )

    # Create health table
    health_table = Table(
        table_data,
        colWidths=[250, 200],
        repeatRows=1,
    )

    health_table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, 0),
                colors.HexColor("#263238"),
            ),
            (
                "TEXTCOLOR",
                (0, 0),
                (-1, 0),
                colors.white,
            ),
            (
                "FONTNAME",
                (0, 0),
                (-1, 0),
                "Helvetica-Bold",
            ),
            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.5,
                colors.grey,
            ),
            (
                "PADDING",
                (0, 0),
                (-1, -1),
                8,
            ),
            (
                "VALIGN",
                (0, 0),
                (-1, -1),
                "MIDDLE",
            ),
            *status_styles,
        ])
    )

    story.append(health_table)
    story.append(Spacer(1, 20))

    # Mitigation section
    story.append(
        Paragraph(
            "Recommended Mitigation",
            styles["Heading2"],
        )
    )
    story.append(Spacer(1, 8))

    story.append(
        Paragraph(
            escape(str(mitigation_summary)),
            styles["Normal"],
        )
    )
    story.append(Spacer(1, 20))

    # Code patch section
    story.append(
        Paragraph(
            "Suggested Code Patch",
            styles["Heading2"],
        )
    )
    story.append(Spacer(1, 8))

    story.append(
        Preformatted(
            str(code_patch),
            code_style,
        )
    )
    story.append(Spacer(1, 20))

    # Footer
    story.append(
        Paragraph(
            "<i>Generated by ChaosKernel - Adversarial SRE Engine</i>",
            styles["Italic"],
        )
    )

    # Generate the PDF
    document.build(story)

    return os.path.abspath(output_path)
